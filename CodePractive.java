public class CodePractive {
    public static void main(String[] args) {

        int x = 10;
        int y = 5;

        System.out.println(x + y);
        System.out.println(x - y);
        System.out.println(x * y);
        System.out.println(x / y);
        System.out.println(x % y);

        System.out.println("=========== NEW LINE ===========");
        System.out.println(x > y);
        System.out.println(x < y);
        System.out.println(x == y);
        System.out.println(x != y);

        System.out.println("=========== NEW LINE ===========");
        System.out.println(x > 5 && y < 10);
        System.out.println(x < 5 && y < 10);
        System.out.println(!(x == y));
    }
}
